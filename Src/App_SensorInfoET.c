void TpTable_Find(void)
{
	int16 i;
	uint16 a,b;

	if( g_TpCount < g_TpTableDown )
	{
		g_TpStep = DispRange_ObjDown - 10;	//直接给超出物温的值
	}
	else if( g_TpCount > g_TpTableUp )
	{
		g_TpStep = DispRange_ObjUp + 10;	//直接给超出物温的值
	}
	else
	{
		for(i=0; i<TpTable_Max; i++)
		{
			if(g_TpCount < (int16)TpTable[i])
			{
				break;
			}
		}

		if( i == TpTable_Max )
		{
			g_TpStep = (i - 1 - TpTable_Offset) * (int8)100;
		}
		else
		{
			b = TpTable[i];
			a = b - g_TpCount;
			i = i-1;
			b = b - TpTable[i];
			a = a*100;
			a = a/b;
			//TP表格是从-20开始的；
			i = i + 1 - TpTable_Offset;
			g_TpStep = i * (int8)100 - a;
		}
	}
}

